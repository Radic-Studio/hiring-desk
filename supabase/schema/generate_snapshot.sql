-- Generates supabase/schema/schema_snapshot.sql from the live database catalogue (run in the SQL editor or via the connector;
-- copy the single text value it returns into schema_snapshot.sql). Re-run after every schema change.
-- Covers: extensions, enum types, schemas, tables (columns, defaults, identity, NOT NULL), constraints, indexes, functions,
-- triggers, row-level security and policies, function/schema grants, realtime publication, storage buckets and storage policies.
-- Not covered (dashboard settings, recorded in the restore runbook): Auth providers and URLs, the Send Email hook, edge functions
-- and their secrets, Data API exposed schemas. No data and no secrets are included.
set search_path = pg_catalog;   -- so every definition comes out fully qualified (public.x), whatever order it is replayed in
with
sch as (select unnest(array['public', 'fr_internal']) as s),
ext as (
  select string_agg(format('create extension if not exists %I with schema %I;', e.extname, n.nspname), E'\n' order by e.extname) t
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname not in ('plpgsql', 'pg_graphql', 'pg_stat_statements', 'pgcrypto', 'pgjwt', 'supabase_vault', 'uuid-ossp')),
enums as (
  select string_agg(format('do $e$ begin create type %I.%I as enum (%s); exception when duplicate_object then null; end $e$;', n.nspname, t.typname,
           (select string_agg(quote_literal(enumlabel), ', ' order by enumsortorder) from pg_enum where enumtypid = t.oid)), E'\n' order by t.typname) t
  from pg_type t join pg_namespace n on n.oid = t.typnamespace where t.typtype = 'e' and n.nspname in (select s from sch)),
tabs as (
  select string_agg(format(E'create table if not exists %I.%I (\n%s\n);', n.nspname, c.relname,
           (select string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                     case when a.attidentity = 'a' then ' generated always as identity' when a.attidentity = 'd' then ' generated by default as identity' else '' end,
                     case when d.adbin is not null and a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
                          when d.adbin is not null and a.attidentity = '' and pg_get_expr(d.adbin, d.adrelid) !~ '(public|fr_internal)\.' then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
                     case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)
            from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
            where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped)), E'\n' order by n.nspname, c.relname) t
  from pg_class c join pg_namespace n on n.oid = c.relnamespace where c.relkind = 'r' and n.nspname in (select s from sch)),
late as (   -- defaults that call the app's own functions: set once the functions exist
  select string_agg(format('alter table %I.%I alter column %I set default %s;', n.nspname, c.relname, a.attname, pg_get_expr(d.adbin, d.adrelid)), E'\n' order by c.relname, a.attnum) t
  from pg_attrdef d join pg_attribute a on a.attrelid = d.adrelid and a.attnum = d.adnum join pg_class c on c.oid = d.adrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in (select s from sch) and a.attgenerated = '' and pg_get_expr(d.adbin, d.adrelid) ~ '(public|fr_internal)\.'),
cons as (   -- primary keys and uniques first, then checks, then foreign keys (which need the referenced keys)
  select string_agg(format('alter table %I.%I add constraint %I %s;', n.nspname, c.relname, k.conname, pg_get_constraintdef(k.oid)), E'\n'
           order by case k.contype when 'p' then 0 when 'u' then 1 when 'c' then 2 else 3 end, n.nspname, c.relname, k.conname) t
  from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in (select s from sch) and k.contype in ('p', 'u', 'c', 'f')),
idx as (
  select string_agg(pg_get_indexdef(i.indexrelid) || ';', E'\n' order by n.nspname, c.relname) t
  from pg_index i join pg_class c on c.oid = i.indexrelid join pg_namespace n on n.oid = c.relnamespace
  where n.nspname in (select s from sch) and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)),
fns as (
  select string_agg(pg_get_functiondef(p.oid) || ';', E'\n\n' order by n.nspname, p.proname, p.oid) t
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname in (select s from sch) and p.prokind in ('f', 'p') and not exists (select 1 from pg_depend dp where dp.objid = p.oid and dp.deptype = 'e')),
fgrants as (   -- functions: who may call them (Postgres default is PUBLIC; the app revokes that on most)
  select string_agg(format('revoke all on function %s from public, anon, authenticated;', p.oid::regprocedure)
           || coalesce((select string_agg(format(' grant execute on function %s to %s;', p.oid::regprocedure, case when x.grantee = 0 then 'public' else quote_ident(r.rolname) end), '')
                        from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) x left join pg_roles r on r.oid = x.grantee
                        where x.privilege_type = 'EXECUTE' and (x.grantee = 0 or r.rolname in ('anon', 'authenticated', 'service_role'))), ''), E'\n' order by n.nspname, p.proname) t
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname in (select s from sch) and p.prokind = 'f' and not exists (select 1 from pg_depend dp where dp.objid = p.oid and dp.deptype = 'e')),
trg as (
  select string_agg(pg_get_triggerdef(t.oid) || ';', E'\n' order by c.relname, t.tgname) t
  from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
  where not t.tgisinternal and n.nspname in (select s from sch)),
rls as (
  select string_agg(format('alter table %I.%I enable row level security;', n.nspname, c.relname), E'\n' order by c.relname) t
  from pg_class c join pg_namespace n on n.oid = c.relnamespace where c.relkind = 'r' and c.relrowsecurity and n.nspname in (select s from sch)),
pol as (
  select string_agg(format('create policy %I on %I.%I as %s for %s to %s%s%s;', p.policyname, p.schemaname, p.tablename, p.permissive, p.cmd,
           (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ') from unnest(p.roles) r),
           case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
           case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end), E'\n' order by p.schemaname, p.tablename, p.policyname) t
  from pg_policies p where p.schemaname in ('public', 'storage') and (p.schemaname = 'public' or p.tablename = 'objects')),
pub as (
  select string_agg(format('alter publication supabase_realtime add table %I.%I;', schemaname, tablename), E'\n' order by tablename) t
  from pg_publication_tables where pubname = 'supabase_realtime'),
bkt as (
  select string_agg(format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %s) on conflict (id) do nothing;',
           id, name, public::text, coalesce(file_size_limit::text, 'null'), coalesce(quote_literal(allowed_mime_types::text) || '::text[]', 'null')), E'\n' order by id) t
  from storage.buckets)
select concat_ws(E'\n\n',
  '-- Future Ready Group System: complete database schema snapshot (structure only: no data, no secrets).',
  '-- Generated ' || to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI') || ' UTC from the live project by supabase/schema/generate_snapshot.sql.',
  '-- Restore: run this whole file in the SQL editor of an EMPTY Supabase project, then load data with fr_restore() (see docs/RESTORE_RUNBOOK.md).',
  'set check_function_bodies = off;',
  'create schema if not exists fr_internal;' || E'\n' || 'grant usage on schema fr_internal to authenticated;',
  '-- extensions', (select t from ext),
  '-- types', (select t from enums),
  '-- tables', (select t from tabs),
  '-- constraints', (select t from cons),
  '-- indexes', (select t from idx),
  '-- functions', (select t from fns),
  '-- defaults that use the functions above', (select t from late),
  '-- who may call each function', (select t from fgrants),
  '-- triggers', (select t from trg),
  '-- row-level security', (select t from rls), (select t from pol),
  '-- realtime', 'do $p$ begin if not exists (select 1 from pg_publication where pubname = ''supabase_realtime'') then create publication supabase_realtime; end if; end $p$;', (select t from pub),
  '-- storage buckets (files themselves are not in database backups)', (select t from bkt),
  'reset check_function_bodies;') as snapshot;
